from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "public" / "missions"
OUT = SOURCE / "object-masks"
OUT.mkdir(parents=True, exist_ok=True)


def p(points, w, h):
    return [(round(x * w / 100), round(y * h / 100)) for x, y in points]


def make(name, shapes, order):
    with Image.open(SOURCE / f"{name}.webp") as source:
        w, h = source.size
    mask = Image.new("L", (w, h), 0)
    draw = ImageDraw.Draw(mask)
    for label in order:
        for kind, data in shapes[label]:
            fill = label * 20
            if kind == "poly":
                draw.polygon(p(data, w, h), fill=fill)
            elif kind == "ellipse":
                x1, y1, x2, y2 = data
                draw.ellipse((x1*w/100, y1*h/100, x2*w/100, y2*h/100), fill=fill)
            elif kind == "rect":
                x1, y1, x2, y2 = data
                draw.rounded_rectangle((x1*w/100, y1*h/100, x2*w/100, y2*h/100), radius=max(2, round(w*.008)), fill=fill)
    mask.save(OUT / f"{name}.png", optimize=True)


